create policy "Everyone may list voices"
on public.voices for select to anon, authenticated
using (true);

create policy "Published companions and own companions are readable"
on public.companions for select to anon, authenticated
using (
  "isPublish" is true
  or (
    (select auth.jwt() ->> 'sub') is not null
    and author = (select auth.jwt() ->> 'sub')
  )
);

create policy "Clerk users create only their own companions"
on public.companions for insert to authenticated
with check (author = (select auth.jwt() ->> 'sub'));

create policy "Owners update their companions"
on public.companions for update to authenticated
using (author = (select auth.jwt() ->> 'sub'))
with check (author = (select auth.jwt() ->> 'sub'));

create policy "Owners delete their companions"
on public.companions for delete to authenticated
using (author = (select auth.jwt() ->> 'sub'));

create policy "Bookmarks belong to their Clerk user"
on public.bookmarks for select to authenticated
using ("userId" = (select auth.jwt() ->> 'sub'));

create policy "Users bookmark accessible companions"
on public.bookmarks for insert to authenticated
with check (
  "userId" = (select auth.jwt() ->> 'sub')
  and exists (
    select 1 from public.companions c
    where c.id = "companionId"
      and (c."isPublish" is true
        or c.author = (select auth.jwt() ->> 'sub'))
  )
);

create policy "Users remove only their own bookmarks"
on public.bookmarks for delete to authenticated
using ("userId" = (select auth.jwt() ->> 'sub'));

-- Transcript rows are NEVER publicly selectable, even when isPublish=true.
-- Public recent-session cards are served via the limited function below.
create policy "Users read only their session transcripts"
on public."session-history" for select to authenticated
using (user_id = (select auth.jwt() ->> 'sub'));

create policy "Users create only their session transcripts"
on public."session-history" for insert to authenticated
with check (
  user_id = (select auth.jwt() ->> 'sub')
  and exists (
    select 1 from public.companions c
    where c.id = companion_id
      and (c."isPublish" is true
        or c.author = (select auth.jwt() ->> 'sub'))
  )
);

create policy "Users update only their session transcripts"
on public."session-history" for update to authenticated
using (user_id = (select auth.jwt() ->> 'sub'))
with check (user_id = (select auth.jwt() ->> 'sub'));

create policy "Users delete only their session transcripts"
on public."session-history" for delete to authenticated
using (user_id = (select auth.jwt() ->> 'sub'));

-- Return only already-public companion data, NEVER messages or user IDs.
-- SECURITY DEFINER is intentional: anonymous homepage visitors cannot read
-- session-history rows directly under the RLS policy above.
create function public.get_recent_published_session_companions(
  max_results integer default 10
)
returns setof public.companions
language sql stable security definer
set search_path = ''
as $$
  select c.*
  from public."session-history" s
  join public.companions c on c.id = s.companion_id
  where s."isPublish" is true
    and c."isPublish" is true
  order by s.created_at desc
  limit least(greatest(coalesce(max_results, 10), 0), 100);
$$;

revoke all on function public.get_recent_published_session_companions(integer)
  from public;
grant execute on function public.get_recent_published_session_companions(integer)
  to anon, authenticated;
